"use client";

import { Collapse, Field, Grid2, Panel, Pill, Rows, Stats } from "@/components/desk/kit";
import { PageHeader } from "@/components/layout/page-header";
import { Avatar } from "@/components/ui/avatar";
import { Button } from "@/components/ui/button";
import { Input, Select } from "@/components/ui/input";
import { CRITERIA, DOCS, useDesk } from "@/lib/desk";
import { downloadPdf } from "@/lib/files";
import { formatStamp } from "@/lib/format";
import { useHrms } from "@/lib/store";
import { useState } from "react";
import { toast } from "sonner";

/* Interview scheduling, the panel's score sheet, document checks and the offer letter. */
export default function InterviewsPage() {
  const role = useHrms((s) => s.actingRole);
  const candidates = useHrms((s) => s.candidates);
  const openings = useHrms((s) => s.openings);
  const employees = useHrms((s) => s.employees);
  const moveCandidate = useHrms((s) => s.moveCandidate);
  const desk = useDesk();
  const [open, setOpen] = useState<string | null>(desk.interviews[0]?.id ?? null);
  const [form, setForm] = useState({ candidateId: "", at: "2026-10-31T10:30", p1: "e-arup", p2: "e-bhaskar" });
  const canEdit = role === "recruiter" || role === "hr_admin";

  const cand = (id: string) => candidates.find((c) => c.id === id);
  const post = (id?: string) => openings.find((o) => o.id === id);
  const ename = (id: string) => employees.find((e) => e.id === id)?.name ?? id;
  const unscheduled = candidates.filter((c) => (c.stage === "shortlist" || c.stage === "interview") && !desk.interviews.some((i) => i.candidateId === c.id));
  const panelists = employees.filter((e) => e.cadre === "executive" && !e.id.startsWith("g-")).slice(0, 12);
  const total = (s: Record<string, number>) => CRITERIA.reduce((n, k) => n + (s[k] ?? 0), 0);

  // Ranked by panel score, then GATE score: the order offers and the waiting list follow.
  const ranked = desk.interviews
    .filter((i) => CRITERIA.every((k) => i.scores[k]))
    .map((i) => ({ ...i, total: total(i.scores), c: cand(i.candidateId) }))
    .sort((a, b) => b.total - a.total || (b.c?.gateScore ?? 0) - (a.c?.gateScore ?? 0));

  function offer(id: string) {
    const iv = desk.interviews.find((i) => i.id === id)!;
    const c = cand(iv.candidateId)!;
    const o = post(c.openingId);
    downloadPdf(`offer-${c.name.toLowerCase().replace(/\s+/g, "-")}`, [
      "Numaligarh Refinery Limited",
      "Human Resources, Numaligarh, Golaghat, Assam 785699",
      "",
      `Offer of appointment: ${o?.post ?? "Engineer"} (${o?.grade ?? "E1"})`,
      "",
      `Dear ${c.name},`,
      "",
      `We are pleased to offer you the post of ${o?.post ?? "Engineer"} in grade ${o?.grade ?? "E1"},`,
      "subject to medical fitness, police verification and original documents.",
      "Please report to HR, Numaligarh, within 30 days of this letter.",
      "",
      "Demo document generated by NRL People. Not a valid offer.",
    ]);
    desk.issueOffer(id);
    moveCandidate(c.id, "offer");
    toast.success(`Offer letter for ${c.name} downloaded`);
  }

  return (
    <div className="space-y-6">
      <PageHeader title="Interviews" subtitle="Schedule the panel, record scores, check documents and issue the offer." />

      <Stats
        items={[
          { label: "Scheduled", value: desk.interviews.filter((i) => !CRITERIA.every((k) => i.scores[k])).length },
          { label: "Scored", value: ranked.length },
          { label: "Offers issued", value: desk.interviews.filter((i) => i.offerAt).length, tone: "ok" },
          { label: "To schedule", value: unscheduled.length, tone: unscheduled.length ? "warn" : "ok" },
        ]}
      />

      <Grid2 className="xl:grid-cols-[minmax(0,1.5fr)_minmax(0,1fr)]">
        <Panel title="Panel sheets">
          <Rows
            items={desk.interviews}
            empty="No interviews yet."
            render={(i) => {
              const c = cand(i.candidateId);
              const docs = DOCS.filter((d) => i.docs[d]).length;
              const scored = CRITERIA.every((k) => i.scores[k]);
              return (
                <div className="w-full">
                  <button type="button" className="flex w-full items-center justify-between gap-3 text-left" onClick={() => setOpen(open === i.id ? null : i.id)}>
                    <span className="flex min-w-0 items-center gap-3">
                      <Avatar name={c?.name ?? "?"} size={34} />
                      <span className="min-w-0">
                        <span className="block truncate text-sm font-medium text-ink">{c?.name}</span>
                        <span className="block truncate text-[12px] text-muted">
                          {post(c?.openingId)?.post}, {formatStamp(i.at)}
                        </span>
                      </span>
                    </span>
                    <span className="flex shrink-0 gap-1.5">
                      <Pill tone={docs === DOCS.length ? "ok" : "muted"}>
                        {docs} of {DOCS.length} documents
                      </Pill>
                      {i.offerAt ? <Pill tone="ok">Offer sent</Pill> : scored ? <Pill tone="brand">{total(i.scores)} of 30</Pill> : <Pill tone="warn">Not scored</Pill>}
                    </span>
                  </button>
                  <Collapse open={open === i.id}>
                    <div className="mt-4 grid gap-6 border-t border-fill pt-4 md:grid-cols-2">
                      <div>
                        <p className="mb-2 text-[13px] text-muted">Panel: {i.panel.map(ename).join(", ")}</p>
                        <div className="space-y-2.5">
                          {CRITERIA.map((k) => (
                            <div key={k} className="flex items-center justify-between gap-3">
                              <span className="text-sm text-ink">{k}</span>
                              <Select
                                disabled={!canEdit || !!i.offerAt}
                                value={i.scores[k] ?? ""}
                                onChange={(e) => desk.score(i.id, k, Number(e.target.value))}
                                className="h-9 w-20"
                                aria-label={`${k} score`}
                              >
                                <option value="">-</option>
                                {Array.from({ length: 10 }, (_, n) => (
                                  <option key={n + 1} value={n + 1}>
                                    {n + 1}
                                  </option>
                                ))}
                              </Select>
                            </div>
                          ))}
                        </div>
                      </div>
                      <div>
                        <p className="mb-2 text-[13px] text-muted">Documents verified</p>
                        <div className="space-y-1">
                          {DOCS.map((d) => (
                            <label key={d} className="flex cursor-pointer items-center gap-2.5 rounded-lg px-1 py-1.5 text-sm">
                              <input type="checkbox" className="h-4 w-4 accent-[var(--brand)]" disabled={!canEdit} checked={!!i.docs[d]} onChange={() => desk.tickDoc(i.id, d)} />
                              {d}
                            </label>
                          ))}
                        </div>
                      </div>
                      {canEdit && !i.offerAt && (
                        <div className="md:col-span-2">
                          <Button disabled={!scored || docs < DOCS.length} onClick={() => offer(i.id)}>
                            Generate offer letter
                          </Button>
                          {(!scored || docs < DOCS.length) && <p className="mt-2 text-[12px] text-muted">Needs all three scores and every document checked.</p>}
                        </div>
                      )}
                    </div>
                  </Collapse>
                </div>
              );
            }}
          />
        </Panel>

        <div className="grid gap-5">
          {canEdit && (
            <Panel title="Schedule">
              <form
                className="grid gap-4"
                onSubmit={(e) => {
                  e.preventDefault();
                  if (!form.candidateId) return toast.error("Pick a candidate.");
                  desk.schedule({ candidateId: form.candidateId, at: `${form.at}:00+05:30`, panel: [form.p1, form.p2] });
                  moveCandidate(form.candidateId, "interview");
                  toast.success("Interview scheduled. The panel is notified.");
                  setForm({ ...form, candidateId: "" });
                }}
              >
                <Field label="Candidate">
                  <Select value={form.candidateId} onChange={(e) => setForm({ ...form, candidateId: e.target.value })}>
                    <option value="">{unscheduled.length ? "Choose" : "Everyone shortlisted is scheduled"}</option>
                    {unscheduled.map((c) => (
                      <option key={c.id} value={c.id}>
                        {c.name}
                      </option>
                    ))}
                  </Select>
                </Field>
                <Field label="Date and time">
                  <Input type="datetime-local" value={form.at} onChange={(e) => setForm({ ...form, at: e.target.value })} />
                </Field>
                <div className="grid gap-4 sm:grid-cols-2">
                  {(["p1", "p2"] as const).map((k, n) => (
                    <Field key={k} label={`Panelist ${n + 1}`}>
                      <Select value={form[k]} onChange={(e) => setForm({ ...form, [k]: e.target.value })}>
                        {panelists.map((p) => (
                          <option key={p.id} value={p.id}>
                            {p.name}
                          </option>
                        ))}
                      </Select>
                    </Field>
                  ))}
                </div>
                <div>
                  <Button type="submit">Schedule</Button>
                </div>
              </form>
            </Panel>
          )}

          <Panel title="Merit order" note="Panel score, then GATE score. Offers go top down; the rest wait in this order.">
            <ol className="space-y-2">
              {ranked.map((r, n) => (
                <li key={r.id} className="flex items-center justify-between gap-3 text-sm">
                  <span className="min-w-0 truncate">
                    <span className="mr-2 tabular-nums text-muted">{n + 1}</span>
                    {r.c?.name}
                  </span>
                  <span className="tabular-nums text-muted">
                    {r.total} of 30, GATE {r.c?.gateScore ?? "n/a"}
                  </span>
                </li>
              ))}
              {ranked.length === 0 && <p className="text-sm text-muted">Scores appear here once a panel finishes.</p>}
            </ol>
          </Panel>
        </div>
      </Grid2>
    </div>
  );
}
